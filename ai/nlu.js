export function parseDuration(s) {
  let t = 0, hit = false, m;
  if ((m = /(\d+(?:\.\d+)?)\s*(?:時間|じかん)(半)?/.exec(s))) { t += parseFloat(m[1]) * 3600 + (m[2] ? 1800 : 0); hit = true; }
  if ((m = /(\d+(?:\.\d+)?)\s*(?:分|ふん|ぷん)(半)?(?!の\d)/.exec(s))) { t += parseFloat(m[1]) * 60 + (m[2] ? 30 : 0); hit = true; }
  if ((m = /(\d+)\s*(?:秒|びょう)/.exec(s))) { t += parseInt(m[1], 10); hit = true; }
  if (!hit && (m = /半(?:時間|じかん)/.exec(s))) { t = 1800; hit = true; }
  return hit && t > 0 ? Math.round(t) : null;
}
const DAYS = { '日': 0, '月': 1, '火': 2, '水': 3, '木': 4, '金': 5, '土': 6 };
export function parseDays(s) {
  if (/毎日|まいにち|毎朝|毎晩|毎夜/.test(s)) return [0, 1, 2, 3, 4, 5, 6];
  if (/平日|へいじつ/.test(s)) return [1, 2, 3, 4, 5];
  if (/土日|週末|しゅうまつ|休日/.test(s)) return [0, 6];
  const m = /毎週\s*([日月火水木金土](?:[・と]?[日月火水木金土])*)\s*曜/.exec(s);
  if (m) return [...new Set([...m[1]].filter(c => c in DAYS).map(c => DAYS[c]))].sort();
  return null;
}
/* 時刻。{h, m, ampm:true なら午前午後がはっきりしている} */
export function parseClock(s, now = new Date()) {
  const m = /(午前|午後|朝|夜|夕方|昼|深夜|ごぜん|ごご|あさ|よる|ゆうがた|ひる)?\s*の?\s*(\d{1,2})\s*(?:時|:|：)\s*(?:(\d{1,2})\s*分?|(半))?/.exec(s);
  if (!m) return null;
  let h = parseInt(m[2], 10); const mi = m[4] ? 30 : (m[3] ? parseInt(m[3], 10) : 0);
  if (h > 24 || mi > 59) return null;
  const mark = m[1] || ''; let sure = !!mark || h >= 13 || h === 0;
  if (/午後|ごご|夜|よる|夕方|ゆうがた/.test(mark) && h < 12) h += 12;
  if (/深夜/.test(mark) && h === 12) h = 0;
  if (/昼|ひる/.test(mark) && h < 6) h += 12;
  if (h === 24) h = 0;
  if (!sure && h >= 1 && h <= 11) {      // 「3時」だけ：もう過ぎていて、午後ならまだ先のときは午後とみなす
    const cur = now.getHours() * 60 + now.getMinutes();
    if (h * 60 + mi <= cur && (h + 12) * 60 + mi > cur) h += 12;
  }
  return { h, m: mi, text: pad2(h) + ':' + pad2(mi), sure };
}
