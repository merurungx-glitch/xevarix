/* ── 漢数字 → 数字（単位の前にあるものだけ） ── */
const KD = { '〇': 0, '零': 0, '一': 1, '二': 2, '三': 3, '四': 4, '五': 5, '六': 6, '七': 7, '八': 8, '九': 9 };
function kanjiNum(s) {
  let total = 0, cur = 0;
  for (const c of s) {
    if (c in KD) cur = cur * 10 + KD[c];
    else if (c === '十') { total += (cur || 1) * 10; cur = 0; }
    else if (c === '百') { total += (cur || 1) * 100; cur = 0; }
    else if (c === '千') { total += (cur || 1) * 1000; cur = 0; }
  }
  return total + cur;
}
const UNIT_AHEAD = '(?=\\s*(時間|時|分|秒|日|週|か月|ヶ月|ヵ月|年|%|％|ぱーせんと|割|回|倍|個|本|枚|円|番|乗|人|つ|度|きろ|めーとる|ぐらむ))';
export function norm(text) {
  let s = normJa(text).replace(/[、，,。．!！?？「」『』（）()〜~…・]/g, m => (m === '?' || m === '？' ? '?' : ' ')).replace(/\s+/g, ' ').trim();
  s = s.replace(new RegExp('([〇零一二三四五六七八九十百千]+)' + UNIT_AHEAD, 'g'), (m, k) => String(kanjiNum(k)));
  s = s.replace(/(\d)\s+(?=(時間|時|分|秒|%))/g, '$1');
  return s;
}
