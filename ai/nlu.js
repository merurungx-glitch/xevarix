/* 日付のことば → Date（「来週の金曜」「3日後」「明日」） */
export function parseDate(s, now = new Date()) {
  const d = new Date(now.getFullYear(), now.getMonth(), now.getDate()); let m;
  const rel = { 'きょう': 0, '今日': 0, '本日': 0, 'あした': 1, 'あす': 1, '明日': 1, 'あさって': 2, '明後日': 2, 'しあさって': 3, 'きのう': -1, '昨日': -1, 'おととい': -2, '一昨日': -2 };
  for (const k in rel) if (s.includes(k)) { d.setDate(d.getDate() + rel[k]); return d; }
  if ((m = /(\d+)\s*日\s*(後|ご|前|まえ)/.exec(s))) { d.setDate(d.getDate() + parseInt(m[1], 10) * (/前|まえ/.test(m[2]) ? -1 : 1)); return d; }
  if ((m = /(\d+)\s*週間?\s*(後|ご|前|まえ)/.exec(s))) { d.setDate(d.getDate() + 7 * parseInt(m[1], 10) * (/前|まえ/.test(m[2]) ? -1 : 1)); return d; }
  if ((m = /(今週|来週|再来週|先週|こんしゅう|らいしゅう|さらいしゅう|せんしゅう)?\s*の?\s*([日月火水木金土])\s*曜/.exec(s))) {
    const w = { '今週': 0, 'こんしゅう': 0, '来週': 1, 'らいしゅう': 1, '再来週': 2, 'さらいしゅう': 2, '先週': -1, 'せんしゅう': -1 }[m[1] || ''];
    const target = DAYS[m[2]];
    if (w === undefined) { let diff = (target - d.getDay() + 7) % 7; if (diff === 0) diff = 7; d.setDate(d.getDate() + diff); }
    else d.setDate(d.getDate() - d.getDay() + target + w * 7);
    return d;
  }
  if ((m = /(?:(\d{4})\s*年)?\s*(\d{1,2})\s*月\s*(\d{1,2})\s*日/.exec(s))) {
    const t = new Date(m[1] ? parseInt(m[1], 10) : d.getFullYear(), parseInt(m[2], 10) - 1, parseInt(m[3], 10));
    if (!m[1] && t < d && /あと|まで|次の/.test(s)) t.setFullYear(t.getFullYear() + 1);
    return t;
  }
  if ((m = /(来月|今月|らいげつ|こんげつ)\s*の?\s*(\d{1,2})\s*日/.exec(s))) return new Date(d.getFullYear(), d.getMonth() + (/来月|らいげつ/.test(m[1]) ? 1 : 0), parseInt(m[2], 10));
  return null;
}

/* 話しことばの計算 → 式（「12かける8」「3の2乗」「ルート2」） */
export function spokenMath(s) {
  return s.replace(/たす|足す|ぷらす/g, '+').replace(/ひく|引く|まいなす/g, '-').replace(/かける|掛ける|×/g, '*').replace(/わる|割る|÷/g, '/')
    .replace(/の\s*(\d+)\s*乗/g, '^$1').replace(/るーと\s*(\d+(?:\.\d+)?)/g, 'sqrt($1)').replace(/ぱーせんと/g, '%')
    .replace(/(は|って)?(いくつ|いくら|何|なに|なん)(ですか|になる|だ)?\??$/g, '').replace(/を?(計算して|けいさんして|教えて)$/g, '').replace(/[=＝]\s*\??$/, '').replace(/\?/g, '').replace(/\s*(は|って|の答え)$/, '').trim();
}

