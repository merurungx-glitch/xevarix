/* ── 分類器（多クラスのロジスティック回帰・文字の2〜3文字の並びが特徴） ── */
const DIM = 4096;
function feats(s) {
  const flat = s.replace(/\s+/g, ''); const out = new Map();
  const add = (k, w) => { let hsh = 2166136261; for (let i = 0; i < k.length; i++) { hsh ^= k.charCodeAt(i); hsh = Math.imul(hsh, 16777619); } const i = (hsh >>> 0) % DIM; out.set(i, (out.get(i) || 0) + w); };
  for (let i = 0; i < flat.length; i++) { add('1' + flat[i], .4); if (i + 1 < flat.length) add('2' + flat.slice(i, i + 2), 1); if (i + 2 < flat.length) add('3' + flat.slice(i, i + 3), 1.2); }
  if (flat.length) { add('^' + flat.slice(0, 2), .8); add('$' + flat.slice(-3), 1.2); }
  let n = 0; for (const v of out.values()) n += v * v; n = Math.sqrt(n) || 1;
  return [...out].map(([i, v]) => [i, v / n]);
}
export class Classifier {
  constructor(labels) { this.labels = labels; this.K = labels.length; this.W = new Float32Array(this.K * DIM); this.b = new Float32Array(this.K); this.trained = 0; }
  scores(f) { const z = new Float32Array(this.K); for (let k = 0; k < this.K; k++) { let s = this.b[k]; const o = k * DIM; for (const [i, v] of f) s += this.W[o + i] * v; z[k] = s; } let m = -Infinity; for (const v of z) if (v > m) m = v; let sum = 0; for (let k = 0; k < this.K; k++) { z[k] = Math.exp(z[k] - m); sum += z[k]; } for (let k = 0; k < this.K; k++) z[k] /= sum; return z; }
  step(f, y, lr) { const p = this.scores(f); for (let k = 0; k < this.K; k++) { const g = p[k] - (k === y ? 1 : 0); if (Math.abs(g) < 1e-4) continue; const o = k * DIM; for (const [i, v] of f) this.W[o + i] -= lr * g * v; this.b[k] -= lr * g * .1; } }
  train(data, epochs = 22, lr = .9) {
    const set = data.map(([t, id]) => [feats(norm(t)), this.labels.indexOf(id)]).filter(x => x[1] >= 0);
    let seed = 12345; const rnd = () => (seed = (seed * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff;
    for (let e = 0; e < epochs; e++) { for (let i = set.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [set[i], set[j]] = [set[j], set[i]]; } const r = lr / (1 + e * .12); for (const [f, y] of set) this.step(f, y, r); }
    this.trained = set.length;
  }
  /* まちがいを直してもらったとき：その文を、正しい意図へ何度か寄せる */
  learn(text, id) { const y = this.labels.indexOf(id); if (y < 0) return; const f = feats(norm(text)); for (let i = 0; i < 6; i++) this.step(f, y, .6); }
  predict(text) { const p = this.scores(feats(norm(text))); return this.labels.map((id, k) => ({ id, p: p[k] })).sort((a, b) => b.p - a.p); }
  dump() { return { W: this.W.buffer.slice(0), b: this.b.buffer.slice(0), K: this.K, n: this.trained }; }
  load(d) { if (!d || d.K !== this.K) return false; this.W = new Float32Array(d.W); this.b = new Float32Array(d.b); this.trained = d.n || 0; return this.W.length === this.K * DIM; }
}
