const seg = (typeof Intl !== 'undefined' && Intl.Segmenter) ? new Intl.Segmenter('ja', { granularity: 'word' }) : null;
const STOP = new Set(['の', 'は', 'が', 'を', 'に', 'で', 'と', 'も', 'て', 'た', 'だ', 'です', 'ます', 'か', 'な', 'ね', 'よ', 'する', 'した', 'して', 'ある', 'いる', 'こと', 'もの', 'これ', 'それ', 'どう', 'なに', '何', 'って', 'から', 'まで', 'ください', '教えて', 'おしえて', 'したい', 'できる', 'できます', 'ですか', 'ますか', 'について']);
export function terms(text) {
  const s = normJa(text); const out = [];
  if (seg) for (const w of seg.segment(s)) { if (w.isWordLike && !STOP.has(w.segment) && w.segment.length > 0) out.push(w.segment); }
  const flat = s.replace(/[^\p{L}\p{N}]/gu, '');
  for (let i = 0; i < flat.length - 1; i++) out.push(flat.slice(i, i + 2));
  return out;
}

